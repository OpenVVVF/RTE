/* Private typedef -----------------------------------------------------------*/
/* Private define ------------------------------------------------------------*/
#define USBD_SERIAL_NUMBER_STRING_LENGTH  26U
#define DEVICE_ID1                        UID_BASE
#define DEVICE_ID2                        (UID_BASE + 4U)
#define DEVICE_ID3                        (UID_BASE + 8U)

/* Private macro -------------------------------------------------------------*/
/* Private function prototypes -----------------------------------------------*/
